const express = require('express');
const router = express.Router ();
const tarefasController = require('../controllers/tarefas.controller')
const validar = require('../middlewares/validar');
const schemas = require('../middlewares/schemas');

//----------------------------------------------------------------------------------------------------------------------------
// ROTA 1 — Listar todas
//----------------------------------------------------------------------------------------------------------------------------

router.get('/', tarefasController.listar);

//----------------------------------------------------------------------------------------------------------------------------
// ROTA 2 — Estatísticas da tarefa
//----------------------------------------------------------------------------------------------------------------------------

router.get('/estatisticas', tarefasController.estatisticas);

//----------------------------------------------------------------------------------------------------------------------------
// ROTA 3 — Buscar tarefa por ID
//----------------------------------------------------------------------------------------------------------------------------

router.get('/:id', tarefasController.buscarPorId);

//----------------------------------------------------------------------------------------------------------------------------
// ROTA 4 — Filtrar por coluna
//----------------------------------------------------------------------------------------------------------------------------

router.get('/', (req, res) => {
    const { coluna, prioridade } = req.query;
    let resultado = tarefas;
    if (coluna) {
        resultado = resultado.filter(t => t.coluna === coluna);
    }
    if (prioridade) {
        resultado = resultado.filter(t => t.prioridade === prioridade);
    }
    res.json(resultado);
});

//----------------------------------------------------------------------------------------------------------------------------
// ROTA 5 — Criar tarefa
//----------------------------------------------------------------------------------------------------------------------------

router.post('/',
    validar(schemas.tarefa),
    tarefasController.criar);

//----------------------------------------------------------------------------------------------------------------------------
// ROTA 6 — Atualizar tarefa
//----------------------------------------------------------------------------------------------------------------------------

router.put('/:id',
    validar(schemas.tarefa),
    tarefasController.atualizar);

//----------------------------------------------------------------------------------------------------------------------------
// ROTA 7 — Deletar tarefa
//----------------------------------------------------------------------------------------------------------------------------

router.delete('/:id', tarefasController.remover);

module.exports = router;